def extract_text_from_image(uploaded_image):
    """Extract text from an email screenshot."""
    image = Image.open(uploaded_image).convert("RGB")

    extracted_text = pytesseract.image_to_string(
        image,
        lang="eng"
    )

    return extracted_text.strip()


def create_scan_report(email_text, scores):
    width, height = 900, 1050

    report = Image.new("RGB", (width, height), "#F4F7FB")
    draw = ImageDraw.Draw(report)

    title_font = ImageFont.truetype(
        r"C:\Windows\Fonts\arial.ttf", 36
    )
    heading_font = ImageFont.truetype(
        r"C:\Windows\Fonts\arial.ttf", 24
    )
    body_font = ImageFont.truetype(
        r"C:\Windows\Fonts\arial.ttf", 18
    )

    is_spam = scores["is_spam"]
    result = "SPAM DETECTED" if is_spam else "LEGITIMATE"
    confidence = (
        scores["spam_prob"]
        if is_spam
        else scores["ham_prob"]
    )

    draw.rounded_rectangle(
        (30, 30, 870, 1020),
        radius=24,
        fill="white",
        outline="#D9E2F0",
        width=3
    )

    draw.text(
        (65, 65), "SpamShield AI",
        fill="#173B70", font=title_font
    )
    draw.text(
        (65, 120), "EMAIL SECURITY SCAN REPORT",
        fill="#52647A", font=body_font
    )
    draw.line(
        (65, 170, 835, 170),
        fill="#D9E2F0", width=3
    )

    result_color = "#B42318" if is_spam else "#147D50"

    draw.text(
        (65, 205), "SCAN RESULT",
        fill="#52647A", font=body_font
    )
    draw.text(
        (65, 245), result,
        fill=result_color, font=heading_font
    )
    draw.text(
        (65, 305),
        f"Classifier confidence: {confidence:.1%}",
        fill="#173B70", font=heading_font
    )
    draw.text(
        (65, 370), "EXTRACTED EMAIL TEXT",
        fill="#52647A", font=body_font
    )

    words = email_text.split()
    lines = []
    current_line = ""

    for word in words:
        candidate = f"{current_line} {word}".strip()

        if draw.textlength(candidate, font=body_font) > 750:
            if current_line:
                lines.append(current_line)
            current_line = word
        else:
            current_line = candidate

    if current_line:
        lines.append(current_line)

    y = 415

    for line in lines:
        if y > 850:
            draw.text(
                (65, y), "... (text shortened to fit report)",
                fill="#52647A", font=body_font
            )
            break

        draw.text(
            (65, y), line,
            fill="#26364A", font=body_font
        )
        y += 30

    draw.line(
        (65, 930, 835, 930),
        fill="#D9E2F0", width=2
    )
    draw.text(
        (65, 950),
        "Generated by SpamShield AI | "
        + datetime.now().strftime("%d %b %Y, %I:%M %p"),
        fill="#52647A", font=body_font
    )

    output = BytesIO()
    report.save(output, format="PNG")

    return output.getvalue()

