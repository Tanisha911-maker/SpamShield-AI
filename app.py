# Simple feature-based Naive Bayes (no external libraries needed)


def tokenize(text: str) -> list[str]:
    text = text.lower()
    text = re.sub(r'[^a-z0-9\s]', ' ', text)
    return text.split()


   
def compute_scores(text: str) -> dict:
    text_lower = text.lower()
    tokens = tokenize(text)
    word_count = len(tokens)

    # Keep keyword matches for the app's existing interface
    spam_hits = [
        kw for kw in SPAM_KEYWORDS if kw in text_lower
    ]
    ham_hits = [
        kw for kw in HAM_KEYWORDS if kw in text_lower
    ]

    # Existing email features
    upper_ratio = sum(1 for c in text if c.isupper()) / max(len(text), 1)
    excl_count = text.count("!")
    dollar_count = text.count("$")
    link_count = len(re.findall(r"http|www|\.com|\.net|bit\.ly", text_lower))

    # Predict using the trained machine-learning model
    probabilities = ML_MODEL.predict_proba([text])[0]
    classes = list(ML_MODEL.classes_)

    spam_prob = float(probabilities[classes.index("spam")])
    ham_prob = float(probabilities[classes.index("ham")])

    return {
        "spam_prob": spam_prob,
        "ham_prob": ham_prob,
        "spam_keywords": spam_hits,
        "ham_keywords": ham_hits,
        "upper_ratio": upper_ratio,
        "excl_count": excl_count,
        "dollar_count": dollar_count,
        "link_count": link_count,
        "word_count": word_count,
        "is_spam": spam_prob >= 0.5,
    }


